/** 依据扩展名推断 mime；未知扩展返回 null（抽取器据此降级为仅元数据）。 */
export function mimeForPath(filePath: string): string | null {
  const ext = path.extname(filePath).toLowerCase();
  return MIME_BY_EXT[ext] ?? null;
}
